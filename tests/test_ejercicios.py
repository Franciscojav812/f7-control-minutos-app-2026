import subprocess, os, threading, http.server, functools, json
from playwright.sync_api import sync_playwright
# Prueba automática (Playwright + Chromium) con datos SINTÉTICOS. Ejecutar: python tests/run_all.py
import tempfile
SP = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.abspath(os.path.join(SP, '..'))
OUT = os.environ.get('TEST_OUT') or tempfile.mkdtemp(prefix='f7tests-')

DATA=subprocess.check_output(['node',os.path.join(SP,'datos_sinteticos.js')]).decode()
class Q(http.server.SimpleHTTPRequestHandler):
    def log_message(self,*a): pass
srv=http.server.ThreadingHTTPServer(('127.0.0.1', 0),functools.partial(Q,directory=SITE)); threading.Thread(target=srv.serve_forever,daemon=True).start()
B = 'http://127.0.0.1:%d' % srv.server_address[1]; fails=[]
def ok(c,m):
    print(('OK   ' if c else 'FALLO')+' '+m)
    if not c: fails.append(m)
with sync_playwright() as p:
    br=p.chromium.launch(); ctx=br.new_context(viewport={'width':390,'height':844},device_scale_factor=2,accept_downloads=True)
    pg=ctx.new_page(); errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.goto(B+'/'); pg.evaluate('d=>localStorage.setItem("f7minutos.club.v2",d)',DATA)
    pg.goto(B+'/ftms/'); pg.wait_for_timeout(400)
    pg.click('nav [data-id=ejer]'); pg.wait_for_timeout(200)
    n_pre=pg.locator('.ej').count(); ok(n_pre==pg.evaluate("EJ.filter(e=>e.cat.includes('pre')).length"), f'lista Prebenjamín con {n_pre} ejercicios')
    pg.screenshot(path=OUT+'/ej_lista.png')
    pg.click('button[data-a=ejcat]'); pg.wait_for_timeout(100); ok(pg.locator('.ej').count()==64,'sin filtro de categoría: 64 ejercicios')
    pg.click('button[data-a=ejf][data-v=remate]'); pg.wait_for_timeout(100); ok(pg.locator('.ej').count()==6,'filtro Remate: 6')
    pg.click('button[data-a=ejn][data-v="2"]'); pg.wait_for_timeout(100); ok(pg.locator('.ej').count()==3,'Remate + Intermedio: 3')
    pg.click('button[data-a=ejf][data-v=""]'); pg.click('button[data-a=ejn][data-v="0"]'); pg.wait_for_timeout(100)
    pg.fill('input[data-ej=q]','rondo'); pg.wait_for_timeout(100)
    vis=pg.locator('.ej:visible').count(); print('rondo visibles',vis); ok(vis>=8 and f'{vis} ejercicios' in pg.inner_text('#ejcount'),'búsqueda "rondo"')
    ok(pg.evaluate('document.activeElement.dataset.ej')=='q','la búsqueda no pierde el foco')
    pg.fill('input[data-ej=q]',''); pg.wait_for_timeout(50)
    pg.click('button[data-a=ejopen][data-id=p4]'); pg.wait_for_timeout(200)
    t=pg.inner_text('#app'); ok('Rondo 4c1' in t and 'OBJETIVO' in t.upper() and 'Organización'.upper() in t.upper() and 'Ficha RFEF'.upper() in t.upper(),'ficha con objetivo, organización y ficha RFEF')
    ok(pg.locator('svg.pitchsvg circle').count()>=5,'dibujo del rondo con jugadores')
    pg.screenshot(path=OUT+'/ej_det.png',full_page=True)
    pg.wait_for_timeout(1400); cap=pg.inner_text('#anicap'); ok('Paso' in cap,'la animación arranca sola ('+cap+')')
    tr0=pg.get_attribute('#p4dj4','transform'); pg.click('#aniplay'); pg.click('button[data-a=anreset]'); pg.wait_for_timeout(50)
    ok('Posición inicial' in pg.inner_text('#anicap'),'reiniciar vuelve a la posición inicial')
    pg.click('button[data-a=annext]'); pg.wait_for_timeout(50); ok(pg.inner_text('#anicap').startswith('Paso 1 de 2'),'paso a paso: siguiente')
    pg.click('button[data-a=annext]'); pg.click('button[data-a=anprev]'); pg.wait_for_timeout(50); ok(pg.inner_text('#anicap').startswith('Paso 1 de 2'),'paso a paso: anterior')
    pg.click('button[data-a=ejstar]'); pg.wait_for_timeout(100); ok('★' in pg.inner_text('button[data-a=ejstar]'),'guardar en favoritos')
    # cronómetro
    pg.click('#tmB'); pg.wait_for_timeout(1300); v=pg.inner_text('#tmV'); ok(v in ('11:59','11:58'),f'cronómetro corre ({v})')
    pg.click('#tmB'); pg.wait_for_timeout(600); v2=pg.inner_text('#tmV'); pg.wait_for_timeout(600); ok(v2==pg.inner_text('#tmV'),'pausa detiene el cronómetro')
    pg.evaluate('()=>{TMR.left=300;TMR.ser=2}'); pg.click('#tmB'); pg.wait_for_timeout(900)
    ok('Serie 2 de 2' in pg.inner_text('#tmS') and pg.inner_text('#tmV')=='12:00','al acabar la serie pasa a la serie 2')
    pg.click('button[data-a=tmreset]'); pg.wait_for_timeout(100)
    # duplicar y editar
    pg.click('button[data-a=ejdup]'); pg.wait_for_timeout(150)
    pg.fill('[data-ef=tit]','Rondo de prueba'); pg.fill('[data-ef=con]','Consigna uno\nConsigna dos'); pg.click('button[data-a=ejsave]'); pg.wait_for_timeout(200)
    t=pg.inner_text('#app'); ok('Rondo de prueba' in t and 'propio' in t and 'Consigna dos' in t and pg.locator('svg.pitchsvg').count()==1,'duplicado propio guardado con dibujo')
    # nuevo sin dibujo
    pg.click('button[data-a=ejback]'); pg.click('button[data-a=ejnew]'); pg.wait_for_timeout(100)
    pg.click('button[data-a=ejsave]'); pg.wait_for_timeout(100); ok('Nuevo ejercicio' in pg.inner_text('#app'),'valida título y objetivo')
    pg.fill('[data-ef=tit]','Ejercicio libre'); pg.fill('[data-ef=obj]','Mejorar el pase'); pg.fill('[data-ef=eje]','Paso 1\nPaso 2'); pg.click('button[data-a=ejsave]'); pg.wait_for_timeout(150)
    ok('Ejercicio libre' in pg.inner_text('#app') and 'Ejercicio sin dibujo' in pg.inner_text('#app'),'ejercicio nuevo sin dibujo')
    pg.reload(); pg.wait_for_timeout(400); pg.click('nav [data-id=ejer]'); pg.wait_for_timeout(150)
    ok(pg.locator('.ej').count()==n_pre+2,'los propios persisten tras recargar')
    pg.click('button[data-a=ejfav]'); pg.wait_for_timeout(100); ok(pg.locator('.ej').count()==1,'filtro Guardados')
    pg.click('button[data-a=ejfav]'); pg.click('button[data-a=ejopen]:has-text("Ejercicio libre")'); pg.wait_for_timeout(100)
    pg.once('dialog',lambda d:d.accept()); pg.click('button[data-a=ejdel]'); pg.wait_for_timeout(150)
    ok(pg.locator('.ej').count()==n_pre+1,'borrar ejercicio propio')
    pg.click('nav [data-id=inicio]'); pg.wait_for_timeout(100)
    with pg.expect_download() as d: pg.click('button[data-a=expFt]')
    d.value.save_as(OUT+'/ftms-copia2.json'); j=json.load(open(OUT+'/ftms-copia2.json'))
    ok(len(j['ejer']['custom'])==1 and 'p4' in j['ejer']['fav'],'la copia FTMS incluye ejercicios y favoritos')
    pg.click('nav [data-id=ejer]'); pg.click('button[data-a=ejcat]'); pg.wait_for_timeout(80)
    pg.click('button[data-a=ejopen][data-id=f1]'); pg.wait_for_timeout(100); t=pg.inner_text('#app')
    ok('Infantil en adelante' in t and 'No lo uses con Prebenjamín' in t and 'Barça Innovation Hub' in t,'físico: aviso infantil y fuente')
    pg.click('button[data-a=ejback]'); pg.click('button[data-a=ejopen][data-id=f4]'); pg.wait_for_timeout(100)
    ok('Ejercicio sin dibujo' in pg.inner_text('#app') and pg.locator('#aniplay').count()==0,'sin dibujo: sin animación')
    # sin datos de minutos
    c2=br.new_context(viewport={'width':390,'height':844}); p2=c2.new_page(); p2.on('pageerror',lambda e: errs.append('c2 '+str(e)))
    p2.goto(B+'/ftms/'); p2.wait_for_timeout(300); p2.click('nav [data-id=ejer]'); p2.wait_for_timeout(150)
    ok(p2.locator('.ej').count()>=30,'Ejercicios funciona sin datos de la app de minutos')
    ok(not errs,'sin errores de JavaScript '+str(errs[:3]))
    br.close()
srv.shutdown(); print('\nRESULTADO:','TODO OK' if not fails else f'{len(fails)} FALLOS'); import sys; sys.exit(1 if fails else 0)
