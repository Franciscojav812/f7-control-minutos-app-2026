import subprocess, sys, os, threading, http.server, functools, tempfile
from playwright.sync_api import sync_playwright
from PIL import Image
# Prueba automática (Playwright + Chromium) con datos SINTÉTICOS: nombre y logo, clubs con escudo y uso sin conexión.
SP = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.abspath(os.path.join(SP, '..'))
OUT = os.environ.get('TEST_OUT') or tempfile.mkdtemp(prefix='f7tests-')
DATA = subprocess.check_output(['node', os.path.join(SP, 'datos_sinteticos.js')]).decode()
class Q(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(Q, directory=SITE))
threading.Thread(target=srv.serve_forever, daemon=True).start()
B = 'http://127.0.0.1:%d' % srv.server_address[1]; fails = []
def ok(c, m):
    print(('OK   ' if c else 'FALLO') + ' ' + m)
    if not c: fails.append(m)
# escudo sintético (rectangular, para comprobar el recorte cuadrado)
CREST = os.path.join(OUT, 'escudo_prueba.png')
im = Image.new('RGB', (300, 200), (30, 90, 200)); im.paste((240, 200, 40), (100, 50, 200, 150)); im.save(CREST)
def ready(pg):
    pg.evaluate('navigator.serviceWorker.ready.then(()=>true)'); pg.wait_for_timeout(300)
with sync_playwright() as p:
    br = p.chromium.launch()
    # ---------- 1) sin conexión desde la primera visita (Táctica nunca abierta con conexión) ----------
    ctx = br.new_context(viewport={'width': 390, 'height': 844}); pg = ctx.new_page(); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(B + '/'); pg.evaluate('d=>localStorage.setItem("f7minutos.club.v2",d)', DATA); pg.reload(); ready(pg)
    ok(pg.title() == 'Banquillo · Minutos' and 'Banquillo · Minutos' in pg.text_content('header'), 'nombre Banquillo en título y cabecera')
    man = pg.evaluate('fetch("manifest.webmanifest").then(r=>r.json())')
    ok(man['short_name'] == 'Banquillo' and any(i['purpose'] == 'maskable' for i in man['icons']), 'manifiesto: Banquillo + icono adaptable')
    ok(pg.evaluate('fetch("icon.svg").then(r=>r.ok)'), 'logo SVG publicado')
    cached = pg.evaluate('caches.keys().then(ks=>Promise.all(ks.map(k=>caches.open(k).then(c=>c.keys()).then(rs=>rs.map(r=>new URL(r.url).pathname))))).then(a=>a.flat())')
    ok('/ftms/index.html' in cached and '/app.js' in cached, 'la instalación guarda también Táctica')
    ctx.set_offline(True)
    pg.reload(); pg.wait_for_timeout(400)
    ok('Prebenjamín A' in pg.inner_text('#app') and pg.locator('.offpill').count() == 1, 'Minutos abre sin conexión y avisa')
    pg.click('nav [data-id=hist]'); pg.wait_for_timeout(100)
    with pg.expect_download() as d: pg.click('button[data-a=xl]')
    ok(d.value.suggested_filename == 'minutos-app.xlsx', 'exporta Excel sin conexión')
    pg.click('a[data-a=ftms]'); pg.wait_for_timeout(600)
    t = pg.text_content('body')
    ok('Banquillo · Táctica' in t and 'Prebenjamín A' in t, 'Táctica abre sin conexión sin haberla visitado antes')
    pg.click('nav [data-id=ejer]'); pg.wait_for_timeout(150)
    ok(pg.locator('.ej').count() > 10, 'ejercicios disponibles sin conexión')
    pg.click('a.hbtn'); pg.wait_for_timeout(400)
    ok('Banquillo · Minutos' in pg.text_content('header'), 'vuelta a Minutos sin conexión')
    ctx.set_offline(False); pg.wait_for_timeout(200)
    ok(pg.locator('.offpill').count() == 0, 'el aviso desaparece al recuperar conexión')
    # ---------- 2) clubs ----------
    pg.click('nav [data-id=setup]'); pg.wait_for_timeout(100)
    opts = pg.eval_on_selector('select[data-a=tclub]', 'e=>[...e.options].map(o=>o.textContent)')
    ok(opts[0] == 'Club San José del Parque', 'club por defecto de los equipos originales')
    pg.select_option('select[data-a=tclub]', '__new'); pg.wait_for_timeout(100)
    pg.fill('#cn', 'CD Prueba Norte'); pg.set_input_files('#cf', CREST); pg.wait_for_timeout(400)
    src = pg.get_attribute('.crestprev', 'src')
    ok(src.startswith('data:image/png'), 'escudo cargado y convertido')
    size = pg.evaluate('s=>new Promise(r=>{const i=new Image();i.onload=()=>r([i.width,i.height]);i.src=s})', src)
    ok(size == [160, 160], 'escudo recortado a 160x160: ' + str(size))
    pg.click('button[data-a=clubsave]'); pg.wait_for_timeout(200)
    hd = pg.text_content('header')
    ok('CD Prueba Norte' in hd and pg.get_attribute('header img', 'src').startswith('data:'), 'cabecera con club y escudo nuevos')
    ok(pg.locator('.clubhd').count() == 2, 'selector agrupado por club')
    pg.reload(); pg.wait_for_timeout(300)
    ok('CD Prueba Norte' in pg.text_content('header'), 'club guardado tras recargar')
    pg.click('nav [data-id=hist]')
    with pg.expect_download() as d: pg.click('button[data-a=xl]')
    ok(d.value.suggested_filename == 'minutos-app.xlsx', 'cambiar de club no cambia los archivos del equipo')
    # equipo nuevo en el otro club
    pg.click('nav [data-id=setup]'); pg.click('button[data-a=tnew]'); pg.wait_for_timeout(100)
    ok(pg.eval_on_selector('#tcl', 'e=>e.selectedOptions[0].textContent') == 'CD Prueba Norte', 'el equipo nuevo propone el club actual')
    pg.fill('#tn', 'Benjamín Sur'); pg.select_option('#tcl', label='Club San José del Parque'); pg.select_option('#tc', 'ben'); pg.fill('#tp', 'bens')
    pg.click('button[data-a=tsave]'); pg.wait_for_timeout(200)
    ok('Club San José del Parque' in pg.text_content('header') and 'Benjamín Sur' in pg.text_content('header'), 'equipo nuevo en el club elegido')
    # Táctica muestra los clubs
    pg.goto(B + '/ftms/'); pg.wait_for_timeout(400)
    ok(pg.locator('.clubhd').count() == 2 and 'CD Prueba Norte' in pg.inner_text('#app'), 'Táctica agrupa los equipos por club')
    pg.click('button[data-a=team][data-id=pre]'); pg.wait_for_timeout(150)
    ok('CD Prueba Norte' in pg.text_content('header') and pg.get_attribute('header img', 'src').startswith('data:'), 'Táctica muestra club y escudo')
    pg.screenshot(path=os.path.join(OUT, 'clubes_tactica.png'))
    # editar: renombrar y quitar escudo
    pg.goto(B + '/'); pg.wait_for_timeout(300)
    pg.click('button[data-a=team][data-id=pre]'); pg.click('nav [data-id=setup]'); pg.click('button[data-a=clubedit]'); pg.wait_for_timeout(100)
    ok(pg.locator('button[data-a=clubdel]').count() == 0, 'no deja borrar un club con equipos')
    pg.fill('#cn', 'CD Prueba Norte B'); pg.click('button[data-a=crestdel]'); pg.wait_for_timeout(100)
    ok(pg.get_attribute('.crestprev', 'src').endswith('icon.svg'), 'sin escudo se usa el logo de la app')
    pg.click('button[data-a=clubsave]'); pg.wait_for_timeout(150)
    ok('CD Prueba Norte B' in pg.text_content('header'), 'club renombrado')
    pg.screenshot(path=os.path.join(OUT, 'clubes_minutos.png'))
    # copia JSON completa incluye los clubs
    pg.click('nav [data-id=hist]')
    js = pg.evaluate('jsonStr()')
    ok('CD Prueba Norte B' in js and '"clubs"' in js, 'la copia JSON completa incluye los clubs')
    # pasar el equipo al club original y borrar el club vacío
    pg.click('nav [data-id=setup]'); pg.select_option('select[data-a=tclub]', 'sjp'); pg.wait_for_timeout(100)
    pg.select_option('select[data-a=tclub]', label='CD Prueba Norte B'); pg.wait_for_timeout(100)
    pg.select_option('select[data-a=tclub]', 'sjp'); pg.wait_for_timeout(100)
    pg.click('button[data-a=clubedit]'); pg.wait_for_timeout(100)
    ok(pg.locator('button[data-a=clubdel]').count() == 0, 'el club original con equipos tampoco se borra')
    pg.click('button[data-a=dcancel]')
    cid = pg.evaluate('Object.keys(ALL.clubs).find(k=>k!=="sjp")')
    pg.evaluate('id=>{DLG={k:"club",id};render()}', cid); pg.on('dialog', lambda dl: dl.accept())
    pg.click('button[data-a=clubdel]'); pg.wait_for_timeout(150)
    ok(pg.evaluate('Object.keys(ALL.clubs).length') == 1 and pg.locator('.clubhd').count() == 0, 'club vacío borrado; selector sin grupos')
    ok(not errs, 'sin errores de JavaScript ' + str(errs[:3]))
    br.close()
srv.shutdown()
print('\nRESULTADO:', 'TODO OK' if not fails else f'{len(fails)} FALLOS'); sys.exit(1 if fails else 0)
